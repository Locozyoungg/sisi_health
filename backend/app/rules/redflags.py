"""Deterministic text red-flag detection (en/sw/sheng), run BEFORE any LLM
(spec 5.2). The urgent-care script is always generated by these patterns plus the
hotline config — the LLM is never in the loop for it."""

import re
from typing import Any

from pydantic import BaseModel

URGENT_CATEGORIES = {
    "severe_acute_pain",
    "heavy_bleeding_dizziness",
    "self_harm",
    # Cervical-screening red flags (spec 5.4.1): abnormal bleeding/discharge always
    # shows the urgent-care script first, before any model or education answer.
    "postcoital_bleeding",
    "intermenstrual_bleeding",
    "postmenopausal_bleeding",
    "unusual_discharge",
}
SAFEGUARDING_CATEGORIES = {"self_harm", "abuse_signal", "pregnancy_concern_minor", "guardian_risk"}


class RedFlagHit(BaseModel):
    pattern_id: str
    category: str
    urgency: str


class RedFlagMatcher:
    def __init__(self, pattern_files: list[dict[str, Any]]) -> None:
        self._patterns: list[tuple[re.Pattern[str], str, str, str]] = []
        for file in pattern_files:
            for entry in file.get("patterns", []):
                self._patterns.append(
                    (
                        re.compile(entry["regex"], re.IGNORECASE),
                        entry["id"],
                        entry["category"],
                        entry["urgency"],
                    )
                )

    def match_text(self, text: str) -> list[RedFlagHit]:
        hits = [
            RedFlagHit(pattern_id=pid, category=cat, urgency=urg)
            for rx, pid, cat, urg in self._patterns
            if rx.search(text)
        ]
        return hits

    def escalations(self, hits: list[RedFlagHit]) -> dict[str, bool]:
        """urgent: red-flag text always shows the urgent-care script first (spec 3.3).
        safeguarding: routes to the safeguarding lead, NEVER a guardian alert."""
        return {
            "urgent": any(h.category in URGENT_CATEGORIES for h in hits),
            "safeguarding": any(h.category in SAFEGUARDING_CATEGORIES for h in hits),
        }
